"use client";

import { useCallback, useEffect, useState } from "react";
import { CharacterTile } from "@/components/CharacterTile";
import { api, type CharacterPage, type CharacterPreview } from "@/lib/api";

export default function DiscoverPage() {
  const [items, setItems] = useState<CharacterPreview[]>([]);
  const [cursor, setCursor] = useState<string | null>(null);
  const [q, setQ] = useState("");
  const [tag, setTag] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);

  const load = useCallback(
    async (append: string | null) => {
      setLoading(true);
      setError(null);
      const params = new URLSearchParams({ limit: "24" });
      if (q.trim()) params.set("q", q.trim());
      if (tag) params.set("tag", tag);
      if (append) params.set("cursor", append);
      try {
        const page = await api<CharacterPage>(`/characters?${params}`);
        setItems((prev) => (append ? [...prev, ...page.items] : page.items));
        setCursor(page.next_cursor ?? null);
      } catch {
        setError("Couldn't load characters. Try again.");
      } finally {
        setLoading(false);
      }
    },
    [q, tag],
  );

  useEffect(() => {
    const t = setTimeout(() => void load(null), 200);
    return () => clearTimeout(t);
  }, [load]);

  const tags = Array.from(new Set(items.flatMap((i) => i.tags))).sort();

  return (
    <div className="flex flex-col gap-6">
      <section>
        <h1 className="text-2xl font-semibold tracking-tight sm:text-3xl">Original AI characters, real conversations</h1>
        <p className="mt-2 max-w-2xl text-ink-muted">
          Every character here is fictional and every reply is generated by AI. Your chats are private to you.
        </p>
      </section>

      <div className="flex flex-col gap-3 sm:flex-row sm:items-center">
        <label className="sr-only" htmlFor="search">
          Search characters
        </label>
        <input id="search" className="field sm:max-w-xs" placeholder="Search by name" value={q} onChange={(e) => setQ(e.target.value)} />
        <div className="flex flex-wrap gap-1.5" role="group" aria-label="Filter by tag">
          {tag && (
            <button className="btn-ghost !px-2.5 !py-1 text-xs" onClick={() => setTag(null)}>
              Clear tag
            </button>
          )}
          {tags.map((t) => (
            <button
              key={t}
              aria-pressed={tag === t}
              onClick={() => setTag(tag === t ? null : t)}
              className={`rounded-full px-2.5 py-1 text-xs ${tag === t ? "bg-accent text-accent-ink" : "bg-surface-2 text-ink-muted hover:text-ink"}`}
            >
              {t}
            </button>
          ))}
        </div>
      </div>

      {error && <p role="alert" className="text-danger">{error}</p>}
      <ul className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3" aria-busy={loading}>
        {items.map((c) => (
          <li key={c.id} className="flex">
            <CharacterTile c={c} />
          </li>
        ))}
      </ul>
      {!loading && items.length === 0 && !error && <p className="text-ink-muted">No characters match.</p>}
      {cursor && (
        <button className="btn-ghost self-center" disabled={loading} onClick={() => void load(cursor)}>
          Load more
        </button>
      )}
    </div>
  );
}
