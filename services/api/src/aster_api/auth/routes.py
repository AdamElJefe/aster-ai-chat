from __future__ import annotations

import re
import uuid
from datetime import datetime
from typing import Literal

from fastapi import APIRouter, Request, Response
from pydantic import BaseModel, Field

from aster_api.age.gate import AccessState, access_state
from aster_api.auth.deps import Ctx, User
from aster_api.auth.sessions import SESSION_COOKIE, create_session, revoke_session
from aster_api.core.audit import audit
from aster_api.core.errors import ApiError
from aster_api.ledger.service import usage_today

router = APIRouter(prefix="/api/v1", tags=["auth"])

HANDLE_RE = re.compile(r"^[a-z0-9_]{3,32}$")


class DevLoginRequest(BaseModel):
    handle: str = Field(min_length=3, max_length=32)


class SessionResponse(BaseModel):
    user_id: uuid.UUID
    handle: str
    csrf_token: str


class Entitlements(BaseModel):
    plan_id: str
    daily_message_limit: int
    messages_used_today: int
    max_message_chars: int


class MeResponse(BaseModel):
    id: uuid.UUID
    handle: str
    role: Literal["user", "admin"]
    region: str
    adult_access: AccessState
    csrf_token: str
    ai_disclosure: str
    entitlements: Entitlements


class DeleteMeRequest(BaseModel):
    confirm_handle: str


def _set_cookie(response: Response, token: str, secure: bool, max_age: int) -> None:
    response.set_cookie(SESSION_COOKIE, token, max_age=max_age, httponly=True, secure=secure, samesite="lax", path="/")


@router.post("/auth/dev/login", response_model=SessionResponse, tags=["dev"])
async def dev_login(body: DevLoginRequest, response: Response, ctx: Ctx) -> SessionResponse:
    """Dev-only identity: logs in (and creates) a user by handle. Disabled unless dev_auth in dev/test."""
    if ctx.settings.auth_provider != "dev_auth" or not ctx.settings.is_dev_like:
        raise ApiError(404, "NOT_FOUND", "not found")
    handle = body.handle.lower()
    if not HANDLE_RE.match(handle):
        raise ApiError(422, "VALIDATION_ERROR", "handle must be 3-32 chars of a-z, 0-9, _")
    async with ctx.db.system() as conn:
        user_id = await conn.fetchval(
            """
            WITH existing AS (
                SELECT u.id FROM identities i JOIN users u ON u.id = i.user_id
                 WHERE i.provider = 'dev_auth' AND i.subject = $1
            ), created AS (
                INSERT INTO users (handle) SELECT $1 WHERE NOT EXISTS (SELECT 1 FROM existing)
                RETURNING id
            ), ident AS (
                INSERT INTO identities (user_id, provider, subject) SELECT id, 'dev_auth', $1 FROM created
            )
            SELECT id FROM existing UNION ALL SELECT id FROM created
            """,
            handle,
        )
        token, csrf = await create_session(conn, user_id, ctx.settings.session_pepper, ctx.settings.session_ttl_hours)
    _set_cookie(response, token, ctx.settings.cookie_secure, ctx.settings.session_ttl_hours * 3600)
    return SessionResponse(user_id=user_id, handle=handle, csrf_token=csrf)


@router.post("/auth/logout", status_code=204)
async def logout(user: User, response: Response, ctx: Ctx) -> Response:
    async with ctx.db.system() as conn:
        await revoke_session(conn, user.session_id)
    response.delete_cookie(SESSION_COOKIE, path="/")
    response.status_code = 204
    return response


@router.get("/me", response_model=MeResponse)
async def me(request: Request, user: User, ctx: Ctx) -> MeResponse:
    region = ctx.region.resolve(request)
    async with ctx.db.tenant(user.id) as conn:
        state = await access_state(conn, ctx.settings, user.id, region)
        plan = await conn.fetchrow("SELECT * FROM plan_definitions WHERE id = $1", user.plan_id)
        used = await usage_today(conn, user.id)
    return MeResponse(
        id=user.id,
        handle=user.handle,
        role=user.role,
        region=region,
        adult_access=state,
        csrf_token=user.csrf_token,
        ai_disclosure="Characters on this service are fictional and every reply is generated by AI.",
        entitlements=Entitlements(
            plan_id=plan["id"],
            daily_message_limit=plan["daily_message_limit"],
            messages_used_today=used,
            max_message_chars=plan["max_message_chars"],
        ),
    )


@router.delete("/me", status_code=204)
async def delete_me(body: DeleteMeRequest, user: User, response: Response, ctx: Ctx) -> Response:
    """Hard-deletes the account and everything it owns. Ledger rows survive pseudonymized."""
    if body.confirm_handle != user.handle:
        raise ApiError(422, "CONFIRMATION_MISMATCH", "type your handle to confirm deletion")
    async with ctx.db.tenant(user.id) as conn:
        await audit(conn, None, "account.deleted", f"deleted-at:{datetime.now().isoformat()}")
    async with ctx.db.system() as conn:
        # users has no RLS; scoped strictly by the authenticated id.
        await conn.execute("DELETE FROM users WHERE id = $1", user.id)
    await ctx.redis.delete(f"rl:send:{user.id}")
    response.delete_cookie(SESSION_COOKIE, path="/")
    response.status_code = 204
    return response
